#!/usr/bin/env node
// Gate a draft and install it as the target: stamp `generated:`, skip no-op
// runs, stop on hand edits, archive the previous version, write the hash header.
//
// Usage: node write.mjs <draft.dbml> <target.dbml> [--force]
// Exit: 0 written or unchanged, 1 gate failed, 2 usage,
//       3 target hand-edited or not generated here (re-run with --force once the user agrees).
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join } from 'node:path';
import { report, validate } from './validate.mjs';

const HEADER = /^\/\/ generated-sha256:[^\n]*\n/;
const HASHED = /^\/\/ generated-sha256: ([0-9a-f]{64})\n/;
const GENERATED = /^([ \t]*generated:[ \t]*).*$/m;
const STAMP = /^[ \t]*generated:[ \t]*(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})/m;

const sha256 = (s) => createHash('sha256').update(s).digest('hex');
const pad = (n) => String(n).padStart(2, '0');
const stamp = (d) =>
  `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
const normalize = (body) => body.replace(GENERATED, '$1*');

const args = process.argv.slice(2);
const force = args.includes('--force');
const [draft, target] = args.filter((a) => a !== '--force');
if (!draft || !target) {
  console.error('usage: node write.mjs <draft.dbml> <target.dbml> [--force]');
  process.exit(2);
}

let body = readFileSync(draft, 'utf8').replace(HEADER, '');
if (!GENERATED.test(body)) {
  console.error(`ERROR  ${draft}  Project note needs a "generated:" line`);
  process.exit(1);
}
body = body.replace(GENERATED, `$1${stamp(new Date())}`);
if (!body.endsWith('\n')) body += '\n';

// Gate the stamped body under the target's name, so the mode matches the target.
const stage = mkdtempSync(join(tmpdir(), 'to-dbml-'));
process.on('exit', () => rmSync(stage, { recursive: true, force: true }));
const staged = join(stage, basename(target));
writeFileSync(staged, body);
const result = validate(staged);
report(result, draft);
if (result.errors.length) process.exit(1);

if (existsSync(target)) {
  const current = readFileSync(target, 'utf8');
  const header = current.match(HASHED);
  const currentBody = current.replace(HEADER, '');

  if (!header || sha256(currentBody) !== header[1]) {
    if (!force) {
      console.error(header ? `${target} was edited after it was generated.` : `${target} was not generated by to-dbml (no hash header).`);
      console.error('Diff, current → new; "-" lines exist only in the current file:');
      const diff = spawnSync('diff', ['-u', target, staged], { stdio: 'inherit' });
      if (diff.error) console.error('(diff unavailable; compare the files by hand)');
      console.error('Re-run with --force to archive the current file and overwrite it.');
      process.exit(3);
    }
  } else if (normalize(currentBody) === normalize(body)) {
    console.log(`no changes since ${currentBody.match(STAMP)?.[1] ?? 'the last run'}: ${target} left untouched`);
    process.exit(0);
  }

  const old = (currentBody.match(STAMP)?.[1] ?? stamp(statSync(target).mtime)).replace(' ', '_').replaceAll(':', '-');
  const versions = join(dirname(target), 'versions');
  mkdirSync(versions, { recursive: true });
  const stem = basename(target, '.dbml');
  let archived = join(versions, `${stem}_${old}.dbml`);
  for (let i = 2; existsSync(archived); i++) archived = join(versions, `${stem}_${old}-${i}.dbml`);
  renameSync(target, archived);
  console.log(`archived ${target} → ${archived}`);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `// generated-sha256: ${sha256(body)}\n${body}`);
console.log(`wrote ${target}`);
